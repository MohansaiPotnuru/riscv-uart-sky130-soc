#!/usr/bin/env python3
"""Generate src/boot_rom.v: a tiny RV32I program that prints a message over the UART.

There is no RISC-V toolchain dependency: the handful of instructions the boot
program needs are encoded directly below, so the ROM can be regenerated with
nothing but Python 3.

Program (RV32I assembly):

        lui   s0, 0x02000        # s0 = UART base 0x0200_0000
    restart:
        addi  s1, zero, MSG      # s1 = pointer to message in ROM
    next:
        lbu   a0, 0(s1)          # a0 = *s1
        beq   a0, zero, restart  # end of string -> start again
    wait:
        lw    t0, 4(s0)          # UART STATUS register
        andi  t0, t0, 1          # bit 0 = TX busy
        bne   t0, zero, wait
        sw    a0, 0(s0)          # UART TXDATA <- byte
        addi  s1, s1, 1
        jal   zero, next

Usage:  python3 firmware/gen_rom.py ["custom message"]
"""
import pathlib
import sys

# ---- register numbers -------------------------------------------------------
ZERO, T0, S0, S1, A0 = 0, 5, 8, 9, 10


# ---- RV32I instruction encoders --------------------------------------------
def _u(v, bits):
    return v & ((1 << bits) - 1)


def i_type(imm, rs1, f3, rd, op):
    return (_u(imm, 12) << 20) | (rs1 << 15) | (f3 << 12) | (rd << 7) | op


def s_type(imm, rs2, rs1, f3, op):
    imm = _u(imm, 12)
    return ((imm >> 5) << 25) | (rs2 << 20) | (rs1 << 15) | (f3 << 12) | ((imm & 0x1F) << 7) | op


def b_type(off, rs2, rs1, f3):
    assert off % 2 == 0 and -4096 <= off < 4096
    o = _u(off, 13)
    return (((o >> 12) & 1) << 31) | (((o >> 5) & 0x3F) << 25) | (rs2 << 20) | (rs1 << 15) \
        | (f3 << 12) | (((o >> 1) & 0xF) << 8) | (((o >> 11) & 1) << 7) | 0b1100011


def j_type(off, rd):
    assert off % 2 == 0
    o = _u(off, 21)
    return (((o >> 20) & 1) << 31) | (((o >> 1) & 0x3FF) << 21) | (((o >> 11) & 1) << 20) \
        | (((o >> 12) & 0xFF) << 12) | (rd << 7) | 0b1101111


def lui(rd, imm20):          return (_u(imm20, 20) << 12) | (rd << 7) | 0b0110111
def addi(rd, rs1, imm):      return i_type(imm, rs1, 0b000, rd, 0b0010011)
def andi(rd, rs1, imm):      return i_type(imm, rs1, 0b111, rd, 0b0010011)
def lbu(rd, rs1, imm):       return i_type(imm, rs1, 0b100, rd, 0b0000011)
def lw(rd, rs1, imm):        return i_type(imm, rs1, 0b010, rd, 0b0000011)
def sw(rs2, rs1, imm):       return s_type(imm, rs2, rs1, 0b010, 0b0100011)
def beq(rs1, rs2, off):      return b_type(off, rs2, rs1, 0b000)
def bne(rs1, rs2, off):      return b_type(off, rs2, rs1, 0b001)
def jal(rd, off):            return j_type(off, rd)


ROM_WORDS = 64  # 256 bytes; must match ROM_WORDS in riscv_uart_soc.v


def build(message: bytes):
    code_words = 10
    msg_addr = code_words * 4
    prog = [
        lui(S0, 0x02000),            # 0x00
        addi(S1, ZERO, msg_addr),    # 0x04 restart
        lbu(A0, S1, 0),              # 0x08 next
        beq(A0, ZERO, 0x04 - 0x0C),  # 0x0C -> restart
        lw(T0, S0, 4),               # 0x10 wait
        andi(T0, T0, 1),             # 0x14
        bne(T0, ZERO, 0x10 - 0x18),  # 0x18 -> wait
        sw(A0, S0, 0),               # 0x1C
        addi(S1, S1, 1),             # 0x20
        jal(ZERO, 0x08 - 0x24),      # 0x24 -> next
    ]
    assert len(prog) == code_words
    data = message + b"\0"
    data += b"\0" * (-len(data) % 4)
    for i in range(0, len(data), 4):  # little-endian packing
        prog.append(int.from_bytes(data[i:i + 4], "little"))
    if len(prog) > ROM_WORDS:
        sys.exit(f"program needs {len(prog)} words, ROM holds {ROM_WORDS}")
    return prog


def emit(words, message):
    lines = [
        "// AUTO-GENERATED by firmware/gen_rom.py - do not edit by hand.",
        f"// Boot program prints: {message!r}",
        "module boot_rom (",
        "    input  wire [5:0]  addr,   // word address",
        "    output reg  [31:0] data",
        ");",
        "    always @(*) begin",
        "        case (addr)",
    ]
    for i, w in enumerate(words):
        lines.append(f"            6'd{i:<2}: data = 32'h{w:08x};")
    lines += [
        "            default: data = 32'h00000013; // nop",
        "        endcase",
        "    end",
        "endmodule",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    msg = sys.argv[1] if len(sys.argv) > 1 else "Hello from RISC-V on SKY130!\r\n"
    out = pathlib.Path(__file__).resolve().parent.parent / "src" / "boot_rom.v"
    out.write_text(emit(build(msg.encode()), msg), newline="\n")
    print(f"wrote {out}")
