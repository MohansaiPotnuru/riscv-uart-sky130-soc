// riscv_uart_soc - PicoRV32 + boot ROM + memory-mapped UART transmitter
//
// Memory map
//   0x0000_0000 - 0x0000_00FF  Boot ROM (64 x 32-bit, read-only, reset vector = 0)
//   0x0200_0000                UART TXDATA  (W: bits[7:0] start a transmission,
//                                            R: last byte written)
//   0x0200_0004                UART STATUS  (R: bit0 = TX busy)
//
// Any other address reads as 0 and ignores writes. Every access completes in
// the same cycle (mem_ready = mem_valid), so there are no wait states.
`default_nettype none

module riscv_uart_soc #(
    parameter integer CLK_FREQ_HZ = 40_000_000, // must match CLOCK_PERIOD in config.json
    parameter integer BAUD_RATE   = 115_200
)(
    input  wire clk,
    input  wire resetn,     // active-low synchronous reset
    output wire tx_out,     // UART TX line (8N1, idle high)
    output wire tx_done     // one-cycle pulse after each stop bit
);

    localparam integer CLKS_PER_BIT = CLK_FREQ_HZ / BAUD_RATE; // 347 @ 40 MHz / 115200

    localparam [31:0] UART_TXDATA = 32'h0200_0000;
    localparam [31:0] UART_STATUS = 32'h0200_0004;

    // ------------------------------------------------------------------
    // PicoRV32 native memory bus
    // ------------------------------------------------------------------
    wire        mem_valid;
    wire        mem_instr;
    wire        mem_ready;
    wire [31:0] mem_addr;
    wire [31:0] mem_wdata;
    wire [ 3:0] mem_wstrb;
    reg  [31:0] mem_rdata;

    assign mem_ready = mem_valid; // zero-wait-state bus

    // ------------------------------------------------------------------
    // Address decode
    // ------------------------------------------------------------------
    wire rom_sel    = (mem_addr[31:8] == 24'h0);
    wire txdata_sel = (mem_addr == UART_TXDATA);
    wire status_sel = (mem_addr == UART_STATUS);

    // ------------------------------------------------------------------
    // Boot ROM (generated by firmware/gen_rom.py)
    // ------------------------------------------------------------------
    wire [31:0] rom_data;

    boot_rom rom (
        .addr (mem_addr[7:2]),
        .data (rom_data)
    );

    // ------------------------------------------------------------------
    // UART registers
    // ------------------------------------------------------------------
    reg        uart_start;
    reg  [7:0] uart_data_reg;
    wire       uart_busy_core;

    // Busy is visible from the cycle after the store until the stop bit has
    // been sent, so firmware can poll STATUS right after writing TXDATA.
    wire uart_busy = uart_start | uart_busy_core;

    always @(posedge clk) begin
        if (!resetn) begin
            uart_start    <= 1'b0;
            uart_data_reg <= 8'h00;
        end else begin
            uart_start <= 1'b0;
            if (mem_valid && txdata_sel && mem_wstrb[0] && !uart_busy) begin
                uart_data_reg <= mem_wdata[7:0];
                uart_start    <= 1'b1;
            end
        end
    end

    // ------------------------------------------------------------------
    // Read-data mux
    // ------------------------------------------------------------------
    always @(*) begin
        if (rom_sel)
            mem_rdata = rom_data;
        else if (txdata_sel)
            mem_rdata = {24'd0, uart_data_reg};
        else if (status_sel)
            mem_rdata = {31'd0, uart_busy};
        else
            mem_rdata = 32'h0000_0000;
    end

    // ------------------------------------------------------------------
    // CPU core (RV32I, minimal configuration for area)
    // ------------------------------------------------------------------
    picorv32 #(
        .ENABLE_COUNTERS   (0),
        .ENABLE_COUNTERS64 (0),
        .BARREL_SHIFTER    (0),
        .ENABLE_FAST_MUL   (0),
        .COMPRESSED_ISA    (0),
        .PROGADDR_RESET    (32'h0000_0000)
    ) cpu (
        .clk       (clk      ),
        .resetn    (resetn   ),
        .mem_valid (mem_valid),
        .mem_instr (mem_instr),
        .mem_ready (mem_ready),
        .mem_addr  (mem_addr ),
        .mem_wdata (mem_wdata),
        .mem_wstrb (mem_wstrb),
        .mem_rdata (mem_rdata),
        .irq       (32'd0    ),
        // Co-processor interface unused (ENABLE_PCPI = 0): tie inputs low
        .pcpi_wr   (1'b0     ),
        .pcpi_rd   (32'd0    ),
        .pcpi_wait (1'b0     ),
        .pcpi_ready(1'b0     )
    );

    // ------------------------------------------------------------------
    // UART transmitter
    // ------------------------------------------------------------------
    uart_tx #(
        .CLKS_PER_BIT (CLKS_PER_BIT)
    ) uart (
        .clk      (clk           ),
        .rst      (!resetn       ),
        .tx_start (uart_start    ),
        .tx_data  (uart_data_reg ),
        .tx_out   (tx_out        ),
        .tx_done  (tx_done       ),
        .tx_busy  (uart_busy_core)
    );

endmodule

`default_nettype wire
